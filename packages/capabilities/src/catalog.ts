function imageService<const Id extends string>(
  id: Id,
  name: string,
  category: Exclude<CapabilityCategory, 'generation'>,
  profileId: string,
  parameters: readonly RequestParameter[],
  seedMaximum?: number,
) {
  return {
    canonicalId: `service/${id}` as const,
    name,
    category,
    invocation: { kind: 'geo-inference-profile' as const, profileId },
    modes: ['image-service'] as const,
    parameters,
    outputFormats: ['jpeg', 'png', 'webp'] as const,
    ...(seedMaximum === undefined ? {} : { seedMaximum }),
  };
}

