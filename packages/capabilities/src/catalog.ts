export type CanonicalCapabilityId = (typeof capabilityCatalog)[number]['canonicalId'];

const canonicalCapabilityIds = new Set<string>(
  capabilityCatalog.map((capability) => capability.canonicalId),
);

export function isCanonicalCapabilityId(value: string): value is CanonicalCapabilityId {
  return canonicalCapabilityIds.has(value);
}
